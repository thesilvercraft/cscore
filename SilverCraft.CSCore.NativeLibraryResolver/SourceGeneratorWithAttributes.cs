using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace SilverCraft.CSCore.NativeLibraryResolver;

/// <summary>
/// A source generator that creates partial class declarations with DllImportResolver methods for annotated classes,
/// and aggregates them into a single global resolver per assembly.
/// </summary>
[Generator]
public class SourceGeneratorWithAttributes : IIncrementalGenerator
{
    private const string Namespace = "Generators";
    private const string AttributeName = "DllImportResolverAttribute";

    private const string AttributeSourceCode = $$"""
        // <auto-generated/>
        namespace {{Namespace}}
        {
            [System.AttributeUsage(System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
            public class {{AttributeName}} : System.Attribute
            {
                public string LibraryName { get; }
                public string DllName { get; }
                public string[] WindowsDlls { get; set; } = [];
                public string[] LinuxDlls { get; set; } = [];
                public string[] MacOsDlls { get; set; } = [];
                public string LinuxInstructions { get; set; } = "";
                public string GenericInstructionsStart { get; set; } = "";
                public string GenericInstructionsWindowsEnd { get; set; } = "";
                public string GenericInstructionsLinuxEnd { get; set; } = "";

                public {{AttributeName}}(string libraryName, string dllName)
                {
                    LibraryName = libraryName;
                    DllName = dllName;
                }
            }
        }
        """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx => ctx.AddSource(
            "DllImportResolverAttribute.g.cs",
            SourceText.From(AttributeSourceCode, Encoding.UTF8)));

        var provider = context.SyntaxProvider
            .CreateSyntaxProvider(
                (s, _) => s is ClassDeclarationSyntax,
                (ctx, _) => GetClassDeclarationForSourceGen(ctx))
            .Where(t => t.reportAttributeFound)
            .Select((t, _) => t.Item1);

        context.RegisterSourceOutput(context.CompilationProvider.Combine(provider.Collect()),
            ((ctx, t) => GenerateCode(ctx, t.Left, t.Right)));
    }

    private static (ClassDeclarationSyntax, bool reportAttributeFound) GetClassDeclarationForSourceGen(
        GeneratorSyntaxContext context)
    {
        var classDeclarationSyntax = (ClassDeclarationSyntax)context.Node;

        foreach (var attributeSyntax in classDeclarationSyntax.AttributeLists.SelectMany(attributeListSyntax => attributeListSyntax.Attributes))
        {
            if (ModelExtensions.GetSymbolInfo(context.SemanticModel, attributeSyntax).Symbol is not IMethodSymbol attributeSymbol)
                continue;

            var attributeName = attributeSymbol.ContainingType.ToDisplayString();
            if (attributeName == $"{Namespace}.{AttributeName}")
                return (classDeclarationSyntax, true);
        }

        return (classDeclarationSyntax, false);
    }

    private void GenerateCode(SourceProductionContext context, Compilation compilation,
        ImmutableArray<ClassDeclarationSyntax> classDeclarations)
    {
        var attributeSymbol = compilation.GetTypeByMetadataName($"{Namespace}.{AttributeName}");
        if (attributeSymbol is null) return;

        // Keep track of the generated classes so we can build the global switch statement
        var generatedResolvers = new List<(string DllName, string FullyQualifiedClass)>();

        foreach (var classDeclarationSyntax in classDeclarations)
        {
            var semanticModel = compilation.GetSemanticModel(classDeclarationSyntax.SyntaxTree);

            if (ModelExtensions.GetDeclaredSymbol(semanticModel, classDeclarationSyntax) is not INamedTypeSymbol classSymbol)
                continue;

            var attributeData = classSymbol.GetAttributes()
                .FirstOrDefault(ad => SymbolEqualityComparer.Default.Equals(ad.AttributeClass, attributeSymbol));

            if (attributeData is null) continue;

            var namespaceName = classSymbol.ContainingNamespace.IsGlobalNamespace
                ? string.Empty
                : classSymbol.ContainingNamespace.ToDisplayString();

            var className = classSymbol.Name;
            var fullyQualifiedClassName = classSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

            var libraryName = attributeData.ConstructorArguments.Length > 0
                ? attributeData.ConstructorArguments[0].Value?.ToString() ?? ""
                : "";

            var dllName = attributeData.ConstructorArguments.Length > 1
                ? attributeData.ConstructorArguments[1].Value?.ToString() ?? ""
                : "";

            var namedArgs = attributeData.NamedArguments.ToDictionary(kv => kv.Key, kv => kv.Value);

            var windowsDlls = GetStringArrayArgument(namedArgs, "WindowsDlls");
            var linuxDlls = GetStringArrayArgument(namedArgs, "LinuxDlls");
            var macOsDlls = GetStringArrayArgument(namedArgs, "MacOsDlls");

            var linuxInstructions = GetStringArgument(namedArgs, "LinuxInstructions");
            var genericInstructionsStart = GetStringArgument(namedArgs, "GenericInstructionsStart");
            var genericInstructionsWindowsEnd = GetStringArgument(namedArgs, "GenericInstructionsWindowsEnd");
            var genericInstructionsLinuxEnd = GetStringArgument(namedArgs, "GenericInstructionsLinuxEnd");

            var startInstructionCode = string.IsNullOrWhiteSpace(genericInstructionsStart)
                ? ""
                : $"Console.Error.WriteLine({SymbolDisplay.FormatLiteral(genericInstructionsStart, true)}, os, cpu);";
            var winEndLiteral = SymbolDisplay.FormatLiteral(genericInstructionsWindowsEnd, true);
            var linuxEndLiteral = SymbolDisplay.FormatLiteral(genericInstructionsLinuxEnd, true);

            var endInstructionCode = "";
            if (!string.IsNullOrWhiteSpace(genericInstructionsWindowsEnd) || !string.IsNullOrWhiteSpace(genericInstructionsLinuxEnd))
            {
                var usesPathWin = genericInstructionsWindowsEnd.Contains("{0}");
                var usesPathLinux = genericInstructionsLinuxEnd.Contains("{0}");

                endInstructionCode = (usesPathWin || usesPathLinux)
                    ? $"Console.Error.WriteLine(OperatingSystem.IsWindows() ? {winEndLiteral} : {linuxEndLiteral}, string.IsNullOrEmpty(assembly?.Location) ? AppContext.BaseDirectory : Path.GetDirectoryName(assembly.Location)!);"
                    : $"Console.Error.WriteLine(OperatingSystem.IsWindows() ? {winEndLiteral} : {linuxEndLiteral});";
            }

            // Save for the global switch resolver. We use dllName because it is the requested library name at runtime.
            if (!string.IsNullOrEmpty(dllName))
            {
                generatedResolvers.Add((dllName, fullyQualifiedClassName));
            }

            var code = $$"""
                         // <auto-generated/>
                         #nullable enable

                         using System;
                         using System.IO;
                         using System.Reflection;
                         using System.Runtime.InteropServices;

                         {{(string.IsNullOrEmpty(namespaceName) ? "" : $"namespace {namespaceName};")}}

                         partial class {{className}}
                         {
                             public static IntPtr DllImportResolver(string libraryName, Assembly assembly, DllImportSearchPath? searchPath)
                             {
                                 if (libraryName != {{SymbolDisplay.FormatLiteral(dllName, true)}}) return IntPtr.Zero;
                                 
                                 string[] candidates = OperatingSystem.IsWindows() switch
                                 {
                                     true => {{FormatStringArrayLiteral(windowsDlls)}},
                                     false when OperatingSystem.IsMacOS() => {{FormatStringArrayLiteral(macOsDlls)}},
                                     _ => {{FormatStringArrayLiteral(linuxDlls)}}
                                 };
                                 
                                 foreach (var candidate in candidates)
                                 {
                                     if (NativeLibrary.TryLoad(candidate, assembly, searchPath, out IntPtr handle))
                                     {
                                         return handle;
                                     }
                                 }
                                 
                                 const string unknown = "unknown";
                                 var os = unknown;
                                 if (OperatingSystem.IsWindows()) os = "windows";
                                 else if (OperatingSystem.IsMacOS()) os = "macos";
                                 else if (OperatingSystem.IsLinux()) os = "linux";
                                 
                                 var cpu = RuntimeInformation.ProcessArchitecture switch
                                 {
                                     Architecture.X64 => "x86_64",
                                     Architecture.Arm64 => "aarch64",
                                     _ => unknown
                                 };
                                 
                                 Console.Error.WriteLine("Could not find " + {{SymbolDisplay.FormatLiteral(libraryName, true)}});
                                 
                                 if (OperatingSystem.IsLinux())
                                 {
                                     Console.Error.WriteLine({{SymbolDisplay.FormatLiteral(linuxInstructions, true)}});
                                 }
                                 
                                 if (os == unknown || cpu == unknown) return IntPtr.Zero;
                                 
                                 {{startInstructionCode}}
                                 {{endInstructionCode}}
                                 
                                 return IntPtr.Zero;
                             }
                         }
                         """;

            context.AddSource($"{className}.DllImportResolver.g.cs", SourceText.From(code, Encoding.UTF8));
        }

        // Generate the Global Resolver if we found any annotated classes
        if (generatedResolvers.Count <= 0) return;
        // Group by DllName to prevent switch duplicate case compilation errors 
        // if two classes map to the exact same library name
        var switchCases = generatedResolvers
            .GroupBy(r => r.DllName)
            .Select(g => 
                $"            {SymbolDisplay.FormatLiteral(g.Key, true)} => {g.First().FullyQualifiedClass}.DllImportResolver(libraryName, assembly, searchPath),");

        var globalCode = $$"""
                           // <auto-generated/>
                           #nullable enable

                           using System;
                           using System.Reflection;
                           using System.Runtime.InteropServices;
                           using System.Runtime.CompilerServices;

                           namespace SilverCraft.NativeLibraryResolvers
                           {
                               public static class GlobalDllImportResolver
                               {
                                   public static IntPtr Resolve(string libraryName, Assembly assembly, DllImportSearchPath? searchPath)
                                   {
                                       return libraryName switch
                                       {
                           {{string.Join("\n", switchCases)}}
                                           _ => IntPtr.Zero
                                       };
                                   }

                                   [ModuleInitializer]
                                   public static void Register()
                                   {
                                       NativeLibrary.SetDllImportResolver(Assembly.GetExecutingAssembly(), Resolve);
                                   }
                               }
                           }
                           """;

        context.AddSource("GlobalDllImportResolver.g.cs", SourceText.From(globalCode, Encoding.UTF8));
    }

    private static string GetStringArgument(Dictionary<string, TypedConstant> namedArgs, string key)
    {
        return namedArgs.TryGetValue(key, out var constant) && constant.Value is string val ? val : string.Empty;
    }

    private static string[] GetStringArrayArgument(Dictionary<string, TypedConstant> namedArgs, string key)
    {
        if (namedArgs.TryGetValue(key, out var constant) && constant is { IsNull: false, Kind: TypedConstantKind.Array })
        {
            return
            [
                .. constant.Values
                    .Select(v => v.Value?.ToString() ?? string.Empty)
            ];
        }
        return [];
    }

    private static string FormatStringArrayLiteral(string[] items)
    {
        if (items.Length == 0) return "[]";
        var literals = items.Select(i => SymbolDisplay.FormatLiteral(i, true));
        return $"[{string.Join<string>(", ", literals)}]";
    }
}